import { useState } from "react";
import { Record, RecordResponse } from "@/lib/types";
import { formatRecordValue } from "@/lib/recordValue";
import RecordForm from "./RecordForm";

interface RecordDetailsProps {
  /** A user record, or a derived DNSSEC row which is shown read-only. */
  record: RecordResponse;
  onRecordChanged: (record: Record) => void;
  defaultEditing?: boolean;
}

export default function RecordDetails({
  record,
  onRecordChanged,
  defaultEditing = false,
}: RecordDetailsProps) {
  const isDerived = record.id == null;
  const canEdit = !isDerived && record.actions.includes("record:update");
  const [isEditing, setIsEditing] = useState(defaultEditing && canEdit);

  if (isEditing && canEdit) {
    return (
      <RecordForm
        // A row with an id is a real user record.
        record={record as Record}
        onSuccess={(updatedRecord) => {
          setIsEditing(false);
          onRecordChanged(updatedRecord);
        }}
        onCancel={() => setIsEditing(false)}
      />
    );
  }

  return (
    <div className="space-y-4">
      <div className="space-y-1">
        <h2 className="text-xl font-bold text-gray-800 sm:text-2xl">
          Record details
        </h2>
        <div className="flex flex-wrap items-center gap-x-2 gap-y-1">
          <p className="min-w-0 text-sm font-medium text-gray-700 wrap-anywhere">
            {record.name}
          </p>
          <span className="rounded-full bg-gray-100 px-2 py-0.5 text-xs font-medium text-gray-600">
            {record.type}
          </span>
          {isDerived && (
            <span className="rounded-full bg-gray-100 px-2 py-0.5 text-xs font-medium text-gray-500">
              Derived
            </span>
          )}
        </div>
      </div>

      {isDerived && (
        <p className="text-sm text-gray-500">
          Generated by the signer; it cannot be edited.
        </p>
      )}

      <div className="space-y-2">
        <div className="p-2.5 bg-gray-50 rounded-md border border-gray-200">
          <p className="text-sm text-gray-500">Value</p>
          <p
            className={`text-gray-900 whitespace-pre-wrap wrap-anywhere ${
              isDerived ? "font-mono text-sm" : "text-base"
            }`}
          >
            {formatRecordValue(record.value, record.type)}
          </p>
        </div>
        <div className="grid grid-cols-2 gap-2">
          <div className="p-2.5 bg-gray-50 rounded-md border border-gray-200">
            <p className="text-sm text-gray-500">Type</p>
            <p className="text-base text-gray-900">{record.type}</p>
          </div>
          <div className="p-2.5 bg-gray-50 rounded-md border border-gray-200">
            <p className="text-sm text-gray-500">TTL</p>
            <p className="text-base text-gray-900">{record.ttl}</p>
          </div>
          {record.priority != null && (
            <div className="p-2.5 bg-gray-50 rounded-md border border-gray-200">
              <p className="text-sm text-gray-500">Priority</p>
              <p className="text-base text-gray-900">{record.priority}</p>
            </div>
          )}
          <div className="col-span-2 rounded-md border border-gray-200 bg-gray-50 p-2.5">
            <p className="text-sm text-gray-500">Zone</p>
            <p className="text-base text-gray-900 wrap-anywhere">
              {record.zone_name}
            </p>
          </div>
        </div>
      </div>

      {canEdit && (
        <div className="flex justify-end">
          <button
            type="button"
            onClick={() => setIsEditing(true)}
            className="btn-primary"
          >
            Edit Record
          </button>
        </div>
      )}
    </div>
  );
}
